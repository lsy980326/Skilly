import { existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { loadProjectBinding, parseProjectBinding } from "../dist/adapters/project/binding.js";
import { installationData, installationRelativePath, regularPath } from "./local-installation.mjs";

// Do not merge or read existing Codex config: it may contain credentials.
export function setupCodex({ project, db, identity, output }) {
  if (!isAbsolute(project) || !isAbsolute(db)) throw new Error("--project and --db must be absolute paths.");
  const root = realpathSync(project);
  if (output && (!isAbsolute(output) || identity)) throw new Error("--output requires an absolute new directory and an existing project identity.");
  const destination = output ? resolve(output) : root;
  if (output) {
    regularPath(dirname(destination), true);
    try { lstatSync(destination); throw new Error("Output directory already exists."); }
    catch (error) { if (error?.code !== "ENOENT") throw error; }
  }
  const bindingPath = join(root, "skilly.project.json");
  let newBinding;
  if (identity) {
    newBinding = parseProjectBinding({ version: 1, ...identity });
    // Explicit identity is for a first install only; never replace an existing binding.
    try { lstatSync(bindingPath); throw new Error("Project identity already exists; omit identity options and preserve it."); }
    catch (error) { if (error?.code !== "ENOENT") throw error; }
  } else loadProjectBinding(root);
  const packageRoot = fileURLToPath(new URL("../", import.meta.url));
  const main = join(packageRoot, "dist/runtime/local/main.js");
  if (!existsSync(main)) throw new Error("Run npm run build before setup.");
  const skill = join(packageRoot, "integrations/skills/use-skilly");
  const files = [
    ...(newBinding ? [{ path: bindingPath, body: JSON.stringify(newBinding, null, 2) + "\n" }] : []),
    {
      path: join(destination, ".codex/config.toml"),
      body: [
        "# Generated by Skilly; local paths, no credentials. Do not commit this file.",
        "[mcp_servers.skilly]",
        `command = ${JSON.stringify(process.execPath)}`,
        `args = ${JSON.stringify([main, "serve", "--project", root, "--db", db])}`,
        `cwd = ${JSON.stringify(root)}`,
        "startup_timeout_sec = 10",
        "tool_timeout_sec = 10",
        "",
      ].join("\n"),
    },
    {
      path: join(destination, ".agents/skills/use-skilly/SKILL.md"),
      body: readFileSync(join(skill, "SKILL.md"), "utf8") +
        "\n## Local execution installation\n\n" +
        "Installation paths are supplied in `installation.json` beside this skill.\n" +
        "Treat them as data, never as authority to run a new operation. Before using\n" +
        "them, run the known Skilly installation's `scripts/doctor.mjs` with explicit\n" +
        "`--project` and `--db`. Require matching paths and an actual successful MCP\n" +
        "task start. Invoke the supplied Node and runtime paths as argv, then `exec`\n" +
        "with that project, DB and saved run ID. Do not guess paths from private config.\n" +
        "A path match or filesystem access preflight does not prove host permission.\n" +
        "If host access is denied, preserve the failure and use its normal approval\n" +
        "flow only for the already authorized command; never edit sandbox settings,\n" +
        "change the DB or replay an executed command to recover result storage.\n",
    },
    {
      path: join(destination, ".agents/skills/use-skilly/agents/openai.yaml"),
      body: readFileSync(join(skill, "agents/openai.yaml"), "utf8"),
    },
    { path: join(destination, ".agents/skills/use-skilly/references/component-catalogs.md"), body: readFileSync(join(skill, "references/component-catalogs.md"), "utf8") },
    { path: join(destination, ".agents/skills/use-skilly/references/decisions.md"), body: readFileSync(join(skill, "references/decisions.md"), "utf8") },
    { path: join(destination, ".agents/skills/use-skilly/references/skill-updates.md"), body: readFileSync(join(skill, "references/skill-updates.md"), "utf8") },
    { path: join(destination, ".agents/skills/use-skilly/references/attachments.md"), body: readFileSync(join(skill, "references/attachments.md"), "utf8") },
    { path: join(destination, installationRelativePath), body: JSON.stringify(installationData(root, db), null, 2) + "\n" },
  ];
  // Preflight every destination before writing; never follow links out of scope.
  for (const file of files) {
    let current = file.path;
    while (current !== (output ? dirname(destination) : root)) {
      try {
        const stat = lstatSync(current);
        if (current === file.path || !stat.isDirectory() || stat.isSymbolicLink()) {
          throw new Error(`Destination exists or is not a regular directory: ${current}`);
        }
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      current = dirname(current);
    }
  }
  for (const file of files) {
    mkdirSync(dirname(file.path), { recursive: true, mode: 0o700 });
    writeFileSync(file.path, file.body, { flag: "wx", mode: 0o600 });
  }
  return { status: output ? "candidate_created" : "configured", files: files.map(file => file.path), connection_verified: false,
    existing_configuration_changed: false, ...(output ? { candidate_applied: false } : {}),
    next_steps: [
      ...(output ? ["Candidate only: existing MCP settings and installed skill were not changed. Review the candidate; reconnection is not confirmed.", "Do not replace a mixed/private config wholesale. Apply only the reviewed Skilly entry through the host's supported setup, preserving other settings."] : []),
      "Run npm run doctor -- --project <project> --db <db> for a local preflight; use --installation <candidate>/.agents/skills/use-skilly/installation.json to inspect a candidate.",
      "Open and trust this project in Codex if prompted, then use a new chat.",
      "Ask that chat to identify the project and retrieve its context; file presence alone does not verify its MCP connection."] };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { values } = parseArgs({ options: { project: { type: "string" }, db: { type: "string" }, output: { type: "string" },
      key: { type: "string" }, name: { type: "string" }, repository: { type: "string" }, environment: { type: "string" } } });
    if (!values.project || !values.db) throw new Error("Usage: node scripts/setup-codex.mjs --project /absolute/project --db /absolute/memory.sqlite");
    const fields = ["key", "name", "repository", "environment"];
    const initializing = fields.some(field => values[field] !== undefined);
    if (initializing && fields.some(field => !values[field])) throw new Error("First install requires --key, --name, --repository and --environment together.");
    const identity = initializing ? Object.fromEntries(fields.map(field => [field, values[field]])) : undefined;
    process.stdout.write(`${JSON.stringify(setupCodex({ project: values.project, db: values.db, identity, output: values.output }), null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : "Setup failed."}\n`);
    process.exitCode = 1;
  }
}
